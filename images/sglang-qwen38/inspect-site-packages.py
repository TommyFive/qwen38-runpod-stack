#!/usr/bin/env python3
"""Report logical sizes of top-level Python site-packages contents.

Read-only and stdlib-only: does not import installed packages, contact any
network endpoint, delete files or follow symlinked directories. Run inside a
test container with the same image under investigation.

  python3 inspect-site-packages.py --path /opt/sglang/lib/python3.12/site-packages --top 30

Logical bytes are not equivalent to compressed registry layer bytes. Sizes
of shared objects may differ greatly when compressed.
"""
import argparse
import json
import os
from pathlib import Path


def allocated_logical_bytes(root: Path) -> int:
    """Count file st_size recursively, excluding symlink targets."""
    stack = [root]
    total = 0
    while stack:
        entry = stack.pop()
        try:
            if entry.is_symlink():
                continue
            if entry.is_file():
                total += entry.stat().st_size
            elif entry.is_dir():
                with os.scandir(entry) as iterator:
                    stack.extend(Path(item.path) for item in iterator)
        except (FileNotFoundError, PermissionError):
            # Concurrent runtime temp files might be removed while counting.
            continue
    return total


def inventory(path: Path):
    if not path.is_dir():
        raise ValueError(f"Missing Python site-packages directory: {path}")
    entries = []
    for child in path.iterdir():
        size = allocated_logical_bytes(child)
        entries.append({"name": child.name, "bytes": size})
    entries.sort(key=lambda row: (-row["bytes"], row["name"]))
    return {"total_bytes": sum(row["bytes"] for row in entries), "entries": entries}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--path", type=Path,
                        default=Path("/opt/sglang/lib/python3.12/site-packages"))
    parser.add_argument("--top", type=int, default=30)
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args()
    if args.top < 1 or args.top > 1000:
        parser.error("--top must be 1..1000")
    try:
        result = inventory(args.path)
    except (OSError, ValueError) as exc:
        parser.error(str(exc))
    if args.json:
        print(json.dumps(result, indent=2))
    else:
        print(f"Python site-packages: {args.path}")
        print(f"Total logical bytes: {result['total_bytes']:,} "
              f"({result['total_bytes']/10**9:.3f} GB)")
        print("Top entries (GB decimal, logical bytes):")
        for row in result["entries"][:args.top]:
            print(f"  {row['bytes']/10**9:8.3f} GB  {row['name']}")
        print("Caution: not compressed layer size; do not delete packages solely by size.")


if __name__ == "__main__":
    main()
