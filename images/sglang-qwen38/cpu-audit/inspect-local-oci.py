#!/usr/bin/env python3
"""Verify exactly one linux/amd64 OCI manifest and calculate compressed layer bytes.

Read-only; does not load/push an image. Handles OCI tar generated by Buildx
--output type=oci,dest=..., with sha256 digests verified for small manifests.
"""
import argparse
import hashlib
import json
import tarfile
from pathlib import Path

BASELINE = 12907436335


def inspect(path):
    with tarfile.open(path, "r:") as archive:
        def readjson(name, expected_hash=None):
            item = archive.extractfile(name)
            if item is None:
                raise ValueError(f"Missing OCI member {name}")
            raw = item.read()
            if expected_hash and hashlib.sha256(raw).hexdigest() != expected_hash:
                raise ValueError(f"Bad SHA256 for {name}")
            return json.loads(raw)

        index = readjson("index.json")
        manifests = index.get("manifests") or []
        candidates = [
            x for x in manifests if x.get("platform", {}).get("os") == "linux"
            and x.get("platform", {}).get("architecture") == "amd64"
        ]
        if not candidates and len(manifests) == 1:
            candidates = manifests
        if len(candidates) != 1:
            raise ValueError(f"Expected one amd64 manifest, got {len(candidates)}")
        descriptor = candidates[0]
        if not descriptor["digest"].startswith("sha256:"):
            raise ValueError("Unexpected manifest digest")
        h = descriptor["digest"].split(":", 1)[1]
        manifest = readjson("blobs/sha256/" + h, h)
        layers = manifest.get("layers") or []
        if not layers:
            raise ValueError("No OCI filesystem layers")
        if any(not x.get("digest", "").startswith("sha256:") for x in layers):
            raise ValueError("Non-sha256 OCI layer")
        compressed = sum(int(x["size"]) for x in layers)
        return {
            "oci_tar": str(path),
            "manifest": descriptor["digest"],
            "config": manifest["config"]["digest"],
            "layers": [{"digest": x["digest"], "bytes": x["size"],
                        "media_type": x["mediaType"]} for x in layers],
            "compressed_layer_bytes": compressed,
            "baseline_v1": BASELINE,
            "delta_bytes": compressed - BASELINE,
            "saving_percent": (BASELINE - compressed) * 100 / BASELINE,
            "note": "Layer descriptor bytes; LOCAL OCI result, NOT a GHCR-published size.",
        }


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("file", type=Path)
    args = p.parse_args()
    print(json.dumps(inspect(args.file), indent=2))
