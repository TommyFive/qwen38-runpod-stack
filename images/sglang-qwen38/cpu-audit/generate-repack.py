#!/usr/bin/env python3
"""Generate faithful CPU-only local repack Dockerfile from v1 image config.

Do not modify published layers. Discard the intermediate base layers by copying
ONLY the pruned merged filesystem into a fresh scratch-based OCI image.

Explicit v1-digest contract; refuse unexpectedly modified source metadata.
No access to GPU, cloud control plane or private credentials.
"""
import argparse
import json
import os
import subprocess
from pathlib import Path

SOURCE = ("ghcr.io/tommyfive/qwen38-sglang@sha256:"
          "1dc683600229c0c34d8df7eb322c6cbf36f677c22d216625df1e3892ae32a7fd")


def inspect():
    out = subprocess.check_output(["docker", "image", "inspect", SOURCE], text=True)
    value = json.loads(out)
    if len(value) != 1 or SOURCE not in value[0].get("RepoDigests", []):
        raise ValueError("Unexpected local v1 image/digest")
    return value[0]["Config"]


def q(value):
    if any(c in value for c in ("\r", "\n", "\0")):
        raise ValueError("Unsafe multiline OCI metadata")
    return json.dumps(value, ensure_ascii=True)


def build(config, mode):
    if config.get("Entrypoint") != ["/opt/nvidia/nvidia_entrypoint.sh"]:
        raise ValueError("Unexpected original entrypoint")
    if config.get("WorkingDir") != "/sgl-workspace/sglang":
        raise ValueError("Unexpected original working directory")
    if mode not in ("rust", "rust-cuda"):
        raise ValueError("Invalid mode")
    lines = [
        "# Autogenerated CPU-only experimental repack; NO GHCR publication.",
        f"FROM {SOURCE} AS prune",
        "RUN --network=none --mount=type=bind,source=prune-candidate.py,target=/tmp/qwen38-prune.py,readonly "
        "python3 /tmp/qwen38-prune.py --mode rust",
    ]
    if mode == "rust-cuda":
        lines.append(
            "RUN --network=none --mount=type=bind,source=prune-candidate.py,target=/tmp/qwen38-prune.py,readonly "
            "python3 /tmp/qwen38-prune.py --mode cuda"
        )
    lines += [
        "FROM scratch",
        "COPY --from=prune / /",
        "LABEL org.opencontainers.image.description=" + q(
            "CPU-only experimental Qwen38 minimal-v2 " + mode + "; NOT GPU tested"
        ),
        "LABEL ai.qwen38.experimental-repack=" + q(mode),
    ]
    for item in config.get("Env") or []:
        key, sep, val = item.partition("=")
        if not sep or not key.replace("_", "a").isalnum():
            raise ValueError("Unsafe original ENV name")
        lines.append(f"ENV {key}={q(val)}")
    for key, value in sorted((config.get("Labels") or {}).items()):
        lines.append(f"LABEL {key}={q(value)}")
    if config.get("User"):
        lines.append("USER " + q(config["User"]))
    if config.get("WorkingDir"):
        lines.append("WORKDIR " + q(config["WorkingDir"]))
    for port in sorted(config.get("ExposedPorts") or {}):
        lines.append("EXPOSE " + port)
    for volume in sorted(config.get("Volumes") or {}):
        lines.append("VOLUME " + q(volume))
    if config.get("StopSignal"):
        lines.append("STOPSIGNAL " + config["StopSignal"])
    if config.get("Entrypoint") is not None:
        lines.append("ENTRYPOINT " + json.dumps(config["Entrypoint"]))
    if config.get("Cmd") is not None:
        lines.append("CMD " + json.dumps(config["Cmd"]))
    return "\n".join(lines) + "\n"


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--mode", choices=["rust", "rust-cuda"], required=True)
    p.add_argument("--output", type=Path, required=True)
    args = p.parse_args()
    config = inspect()
    args.output.write_text(build(config, args.mode), encoding="utf-8")
    print(f"Created {args.output} ({args.mode}); {len(config.get('Env') or [])} ENV keys")


if __name__ == "__main__":
    main()
